import { Link } from "react-router-dom";
import { useQuery } from "@tanstack/react-query";
import { ShieldCheck } from "lucide-react";
import { api } from "@/api/client";
import { Card, CardHeader, EmptyState, ErrorState, PageHeader, Spinner } from "@/components/ui";
import { StatusBadge } from "@/components/StatusBadge";
import { formatDateTime } from "@/lib/format";

export function RemediationsPage() {
  const remediations = useQuery({
    queryKey: ["remediations"],
    queryFn: () => api.listRemediations({ limit: 100 }),
  });

  return (
    <div>
      <PageHeader
        title="Remediation Proposals"
        subtitle="Validated, allowlisted remediation plans generated by the planning agent."
      />

      <Card>
        <CardHeader title="Proposals" subtitle={`${remediations.data?.total ?? 0} total`} />
        {remediations.isLoading ? (
          <Spinner />
        ) : remediations.isError ? (
          <ErrorState message={(remediations.error as Error).message} onRetry={() => remediations.refetch()} />
        ) : remediations.data!.items.length === 0 ? (
          <EmptyState
            title="No remediation proposals"
            description="Run analysis on an incident to generate a remediation plan."
            action={<ShieldCheck className="h-5 w-5 text-slate-300" />}
          />
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full min-w-[860px] text-sm">
              <thead>
                <tr className="border-b border-slate-100 text-left text-xs uppercase tracking-wide text-slate-500">
                  <th className="px-5 py-3 font-medium">Action</th>
                  <th className="px-5 py-3 font-medium">Title</th>
                  <th className="px-5 py-3 font-medium">Risk</th>
                  <th className="px-5 py-3 font-medium">Status</th>
                  <th className="px-5 py-3 font-medium">Approval</th>
                  <th className="px-5 py-3 font-medium">Created</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {remediations.data!.items.map((plan) => (
                  <tr key={plan.id} className="hover:bg-slate-50">
                    <td className="px-5 py-3 font-mono text-xs text-slate-700">{plan.action_id}</td>
                    <td className="px-5 py-3">
                      <Link to={`/incidents/${plan.incident_id}`} className="font-medium text-brand-700 hover:underline">
                        {plan.title}
                      </Link>
                    </td>
                    <td className="px-5 py-3">
                      <StatusBadge value={plan.risk_level} kind="risk" />
                    </td>
                    <td className="px-5 py-3">
                      <StatusBadge value={plan.status} kind="plan" />
                    </td>
                    <td className="px-5 py-3 text-slate-600">
                      {plan.requires_approval ? "Required" : "Not required"}
                    </td>
                    <td className="px-5 py-3 text-slate-500">{formatDateTime(plan.created_at)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </div>
  );
}
